def match(pattern, text):
    found = re.search(pattern, text)
    if found is None:
        raise ValueError(f"missing {pattern!r} in {text[:190]!r}")
    return found.group(1)


def numbers(text):
    return [int(value) for value in re.findall(r"-?\d+", text)]


def boolean(text, yes, no):
    if re.search(no, text):
        return False
    if re.search(yes, text):
        return True
    raise ValueError(f"missing explicit positive or negative result in {text!r}")


def read_json_after(text, marker):
    if marker not in text:
        raise ValueError(f"missing result caption {marker!r} in {text!r}")
    return json.JSONDecoder().raw_decode(text.split(marker, 1)[1].lstrip())[0]


def enum_results(pid, index, result):
    items = result["items"]
    if pid == 51:
        n = [4, 2, 5][index]
        expected = []
        for columns in permutations(range(n)):
            if len({c-r for r,c in enumerate(columns)}) == len({r+c for r,c in enumerate(columns)}) == n:
                expected.append(["."*c + "Q" + "."*(n-1-c) for c in columns])
        return sorted([x.splitlines() for x in items]), sorted(expected)
    actual = sorted(json.loads(item) for item in items)
    if pid == 46:
        n = [3, 4, 1][index]
        expected = [list(row) for row in permutations(range(1, n+1))]
    elif pid == 78:
        n = [3, 1, 4][index]
        expected = [list(row) for k in range(n+1) for row in combinations(range(1,n+1), k)]
    elif pid == 17:
        digits = ["23", "234", "79", "2", ""][index]
        keys = dict(zip("23456789", ["abc","def","ghi","jkl","mno","pqrs","tuv","wxyz"]))
        expected = ["".join(row) for row in product(*(keys[x] for x in digits))] if digits else []
    elif pid == 22:
        n = [3, 1, 4][index]
        expected = []
        for chars in product("()", repeat=2*n):
            score = 0
            for char in chars:
                score += 1 if char == "(" else -1
                if score < 0:
                    break
            else:
                if score == 0:
                    expected.append("".join(chars))
    else:
        expected = [[[2,2,3],[7]], [[2,2,2,2],[2,3,3],[3,5]], [[2,2,2]]][index]
    return actual, sorted(expected)


def array_algorithm(pid, data, result):
    end = result["end"]
    if not data:
        raise ValueError("opening chart has no visible values")
    if pid == 283:
        return result["bars"], [x for x in data if x] + [0]*data.count(0)
    if pid == 11:
        expected = max(min(data[i], data[j])*(j-i) for i,j in combinations(range(len(data)), 2))
        return int(match(r"最大面积 = (\d+)", end)), expected
    if pid == 42:
        water = [min(max(data[:i+1]), max(data[i:]))-x for i,x in enumerate(data)]
        return int(match(r"总共接水 = (\d+)", end)), sum(water)
    expected = {tuple(sorted(triple)) for triple in combinations(data, 3) if sum(triple) == 0}
    actual = [json.loads(a) for a in re.findall(r"\[[-\d, ]+\]", end)]
    return sorted(actual), sorted(map(list, expected))


